import { prisma } from '../lib/prisma';
import { TEAM_MEMBERS, VOICEFRONT_CONTEXT_PACK } from './team-content';
import { callTeamModel, partsToText } from './team-gemini';
import { postGroupStatusLine } from './team.service';

/**
 * The chief of staff loop (Phase 2a). A coordinator routine, run by
 * the team job on a tick and directly by tests, that keeps the work
 * queue moving without a human in the middle:
 *
 *  - ASSIGN: a QUEUED item becomes ASSIGNED. An owner already on the
 *    item is respected; a missing one is picked by keyword rules over
 *    the title and detail (the member whose seat the work belongs to),
 *    falling back to Daniel.
 *  - WORK: the assigned member writes a real output for the item, a
 *    TeamDraft summarizing the item's stored finding and recommending
 *    the next step, generated by that member's model from the item's
 *    own detail. The item moves ASSIGNED to IN_PROGRESS to DONE with
 *    the draft linked on it, and a templated status line lands in the
 *    team channel at pickup and at completion. If the member's model
 *    call fails, the item goes BLOCKED with the reason appended to its
 *    detail. At most MAX_ITEMS_WORKED_PER_TICK items are worked per
 *    tick, so a backlog cannot burn the day in one pass.
 *  - NUDGE: an item IN_PROGRESS for over a day gets one templated
 *    nudge line in the channel per day.
 *
 * Status lines are templates by design (see postGroupStatusLine):
 * they report state, they are not faked conversation. The only model
 * text the coordinator produces is the work draft itself, and a model
 * failure there blocks the item honestly instead of inventing output.
 *
 * The daily digest also lives here: a templated composition of the
 * last 24 hours from the runs ledger, the queue, and the drafts,
 * filed as a DAILY_DIGEST draft authored by the coordinator (member
 * slug 'coordinator'). It is never authored as Cleo and never lands
 * in the CEO channel; the CEO channel stays genuinely the real Cleo.
 */

const DAY_MS = 24 * 60 * 60 * 1000;
export const MAX_ITEMS_WORKED_PER_TICK = 3;

/* --------------------------- owner assignment ---------------------------- */

const OWNER_KEYWORDS: Array<{ slug: string; words: string[] }> = [
  { slug: 'daniel', words: ['leak', 'funnel', 'demo', 'trial', 'minute cap'] },
  { slug: 'priya', words: ['score', 'call quality', 'failure', 'scorecard', 'regression'] },
  { slug: 'layla', words: ['dossier', 'research', 'clinic', 'competitor'] },
  { slug: 'omar', words: ['build', 'code', 'bug', 'uptime', 'deploy', 'api'] },
];

/**
 * Pick the member a work item belongs to from its words. Pure and
 * exported for tests. First matching seat wins; no match falls back
 * to Daniel (the funnel seat, where uncategorized findings land).
 */
export function pickOwnerSlug(title: string, detail?: string | null): string {
  const text = `${title} ${detail ?? ''}`.toLowerCase();
  for (const rule of OWNER_KEYWORDS) {
    if (rule.words.some((word) => text.includes(word))) return rule.slug;
  }
  return 'daniel';
}

/* ------------------------------ coordinator ------------------------------ */

type WorkItemRow = {
  id: string;
  title: string;
  detail: string | null;
  ownerSlug: string;
  status: string;
  updatedAt: Date;
  lastNudgeAt: Date | null;
};

async function memberFor(slug: string) {
  const row = await prisma.teamMember.findUnique({ where: { slug } });
  if (row) return { slug: row.slug, name: row.name, personaPrompt: row.personaPrompt, modelConfig: row.modelConfig };
  const seed = TEAM_MEMBERS.find((member) => member.slug === slug);
  if (!seed) throw new Error(`No team member "${slug}".`);
  return { slug: seed.slug, name: seed.name, personaPrompt: seed.personaPrompt, modelConfig: seed.modelConfig };
}

export interface CoordinatorTickResult {
  assigned: number;
  worked: number;
  blocked: number;
  nudged: number;
  summary: string;
}

/**
 * One coordinator pass. `keyMode` selects the model key for the work
 * drafts: 'shared' (the scheduled path, the paid shared key) or
 * 'member' (the member's own chain, the default for direct calls).
 */
export async function runTeamCoordinator(params: {
  now?: Date;
  keyMode?: 'shared' | 'member';
  maxWork?: number;
} = {}): Promise<CoordinatorTickResult> {
  const now = params.now ?? new Date();
  const maxWork = params.maxWork ?? MAX_ITEMS_WORKED_PER_TICK;
  let assigned = 0;
  let worked = 0;
  let blocked = 0;
  let nudged = 0;

  /* ---- assign everything queued ---- */
  const queued = (await prisma.workItem.findMany({
    where: { status: 'QUEUED' },
    orderBy: { createdAt: 'asc' },
    take: 50,
  })) as WorkItemRow[];
  const toWork: WorkItemRow[] = [];
  for (const item of queued) {
    const ownerSlug = item.ownerSlug?.trim() ? item.ownerSlug : pickOwnerSlug(item.title, item.detail);
    const updated = (await prisma.workItem.update({
      where: { id: item.id },
      data: { status: 'ASSIGNED', ownerSlug },
    })) as WorkItemRow;
    assigned++;
    toWork.push(updated);
  }
  // Items assigned on earlier ticks that nobody worked yet join the
  // work list, oldest first, behind this tick's new assignments.
  const waiting = (await prisma.workItem.findMany({
    where: { status: 'ASSIGNED' },
    orderBy: { createdAt: 'asc' },
    take: 50,
  })) as WorkItemRow[];
  for (const item of waiting) {
    if (!toWork.some((candidate) => candidate.id === item.id)) toWork.push(item);
  }

  /* ---- work up to the per-tick cap ---- */
  for (const item of toWork.slice(0, maxWork)) {
    const member = await memberFor(item.ownerSlug);
    await prisma.workItem.update({ where: { id: item.id }, data: { status: 'IN_PROGRESS' } });
    await postGroupStatusLine({ memberSlug: member.slug, body: `Picked up: ${item.title}` });
    try {
      const parts = await callTeamModel({
        model: member.modelConfig,
        memberSlug: member.slug,
        useSharedKey: params.keyMode === 'shared',
        systemText: `${member.personaPrompt}\n\n${VOICEFRONT_CONTEXT_PACK}`,
        contents: [
          {
            role: 'user',
            parts: [
              {
                text: [
                  `You picked up this work item from the team queue. Write its working output: a short summary of the finding AS STORED BELOW (use only the facts in the item, invent nothing), then the recommended next step and who should take it. Plain text, tight.`,
                  '',
                  `WORK ITEM: ${item.title}`,
                  '',
                  item.detail ?? '(no detail stored)',
                ].join('\n'),
              },
            ],
          },
        ],
      });
      const text = partsToText(parts);
      if (!text) throw new Error('The member produced no output for this item.');
      const draft = await prisma.teamDraft.create({
        data: {
          memberSlug: member.slug,
          kind: 'OTHER',
          title: `Work summary: ${item.title}`.slice(0, 200),
          body: text,
        },
      });
      await prisma.workItem.update({
        where: { id: item.id },
        data: { status: 'DONE', draftId: draft.id },
      });
      await postGroupStatusLine({
        memberSlug: member.slug,
        body: `Done: ${item.title}, draft is in Drafts.`,
      });
      worked++;
    } catch (err) {
      const reason = err instanceof Error ? err.message : String(err);
      await prisma.workItem.update({
        where: { id: item.id },
        data: {
          status: 'BLOCKED',
          detail: `${item.detail ?? ''}\n\nBlocked by the coordinator: ${reason}`.trim().slice(0, 4000),
        },
      });
      blocked++;
    }
  }

  /* ---- nudge stale in-progress items, at most one line per day ---- */
  const staleBefore = new Date(now.getTime() - DAY_MS);
  const inProgress = (await prisma.workItem.findMany({
    where: { status: 'IN_PROGRESS', updatedAt: { lt: staleBefore } },
    orderBy: { updatedAt: 'asc' },
    take: 20,
  })) as WorkItemRow[];
  for (const item of inProgress) {
    if (item.lastNudgeAt && item.lastNudgeAt.getTime() > now.getTime() - DAY_MS) continue;
    await postGroupStatusLine({
      memberSlug: item.ownerSlug,
      body: `Still in progress: ${item.title} (open over a day).`,
    });
    await prisma.workItem.update({ where: { id: item.id }, data: { lastNudgeAt: now } });
    nudged++;
  }

  const summary = `Coordinator: ${assigned} assigned, ${worked} worked to done, ${blocked} blocked, ${nudged} nudged.`;
  return { assigned, worked, blocked, nudged, summary };
}

/* ------------------------------ daily digest ----------------------------- */

/** The score at the end of a scorecard draft title, e.g. "(2/4)". */
function scorecardTitleScore(title: string): number | null {
  const match = title.match(/\((\d)\/4\)\s*$/);
  return match ? Number(match[1]) : null;
}

export interface DailyDigestResult {
  draftId: string;
  title: string;
  exceptions: number;
  summary: string;
}

/**
 * Compose the last 24 hours into one DAILY_DIGEST draft: run counts
 * from the ledger, findings filed, items closed, and the exceptions
 * (any call scored 2 or lower, any leak item, any FAILED run). The
 * digest is templated from records, no model writes it, and its body
 * says plainly that it is automated and not written by Cleo. One
 * templated SYSTEM line in the team channel announces it with the
 * exception count. It never touches the CEO channel.
 */
export async function runDailyDigest(params: { now?: Date } = {}): Promise<DailyDigestResult> {
  const now = params.now ?? new Date();
  const since = new Date(now.getTime() - DAY_MS);
  const inWindow = { gte: since };

  const [runs, itemsFiled, itemsClosed, drafts, scorecards] = await Promise.all([
    prisma.teamRun.findMany({ where: { startedAt: inWindow }, orderBy: { startedAt: 'asc' }, take: 500 }),
    prisma.workItem.findMany({ where: { createdAt: inWindow }, orderBy: { createdAt: 'asc' }, take: 200 }),
    prisma.workItem.findMany({
      where: { status: 'DONE', updatedAt: inWindow },
      orderBy: { updatedAt: 'asc' },
      take: 200,
    }),
    prisma.teamDraft.findMany({ where: { createdAt: inWindow }, take: 500, select: { kind: true } }),
    prisma.teamDraft.findMany({
      where: { createdAt: inWindow, kind: 'SCORECARD' },
      take: 200,
      select: { title: true },
    }),
  ]);

  const runsDone = runs.filter((run) => run.status === 'DONE').length;
  const runsFailed = runs.filter((run) => run.status === 'FAILED');
  const weakScorecards = scorecards.filter((draft) => {
    const score = scorecardTitleScore(draft.title);
    return score !== null && score <= 2;
  });
  const leakItems = itemsFiled.filter((item) => item.title.startsWith('Leak radar:'));
  const exceptions = weakScorecards.length + leakItems.length + runsFailed.length;

  const dateLabel = now.toISOString().slice(0, 10);
  const title = `Daily digest ${dateLabel}`;
  const lines = [
    'Automated daily digest from the team coordinator. Compiled from the runs ledger, the work queue, and the drafts. Not written by Cleo.',
    '',
    `Runs in the last 24 hours: ${runs.length} (${runsDone} done, ${runsFailed.length} failed).`,
    `Findings filed as work items: ${itemsFiled.length}.`,
    `Work items closed: ${itemsClosed.length}.`,
    `Drafts produced: ${drafts.length}.`,
    '',
    `Exceptions (${exceptions}):`,
    ...(weakScorecards.length > 0
      ? weakScorecards.map((draft) => `- Weak call scored: ${draft.title}`)
      : []),
    ...(leakItems.length > 0 ? leakItems.map((item) => `- Leak filed: ${item.title}`) : []),
    ...(runsFailed.length > 0
      ? runsFailed.map((run) => `- Failed run: ${run.ability} (${run.summary ?? 'no summary'})`)
      : []),
    ...(exceptions === 0 ? ['- None.'] : []),
  ];
  const draft = await prisma.teamDraft.create({
    data: { memberSlug: 'coordinator', kind: 'DAILY_DIGEST', title, body: lines.join('\n') },
  });
  await postGroupStatusLine({
    body: `Daily digest is ready in Drafts: ${exceptions} exception(s) in the last 24 hours.`,
  });
  const summary = `Daily digest ${dateLabel}: ${runs.length} runs, ${itemsFiled.length} findings, ${itemsClosed.length} closed, ${exceptions} exception(s).`;
  return { draftId: draft.id, title, exceptions, summary };
}
